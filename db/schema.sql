-- Histórico persistente e simulações
CREATE TABLE IF NOT EXISTS zuz_pricing_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id UUID NOT NULL REFERENCES zuz_companies(id) ON DELETE CASCADE,
  product_id TEXT NOT NULL, product_name TEXT NOT NULL,
  fingerprint TEXT NOT NULL, snapshot JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_zuz_pricing_history_company_product ON zuz_pricing_history(company_id,product_id,id DESC);
CREATE TABLE IF NOT EXISTS zuz_sales_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id UUID NOT NULL REFERENCES zuz_companies(id) ON DELETE CASCADE,
  product_id UUID NOT NULL REFERENCES zuz_products(id) ON DELETE CASCADE,
  period VARCHAR(7) NOT NULL,
  average_price NUMERIC(14,2) NOT NULL CHECK(average_price > 0),
  sold_units INTEGER NOT NULL CHECK(sold_units >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id,product_id,period)
);
CREATE INDEX IF NOT EXISTS idx_zuz_sales_observations_company_product ON zuz_sales_observations(company_id,product_id,period);
CREATE TABLE IF NOT EXISTS zuz_simulations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id UUID NOT NULL REFERENCES zuz_companies(id) ON DELETE CASCADE,
  product_id UUID,
  name VARCHAR(100) NOT NULL,
  snapshot JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_zuz_simulations_company ON zuz_simulations(company_id,created_at DESC);
ALTER TABLE zuz_pricing_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE zuz_sales_observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE zuz_simulations ENABLE ROW LEVEL SECURITY;
