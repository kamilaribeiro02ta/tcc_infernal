"use strict";
const test=require("node:test"),assert=require("node:assert/strict");
const fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"zuni-actions-"));
process.env.ZUZ_SQLITE_DIRECTORY=dir;process.env.NODE_ENV="test";process.env.GEMINI_API_KEY="mock-key";
delete process.env.DATABASE_URL;delete process.env.VERCEL;
const express=require("express"),request=require("supertest");
const {createApi}=require("../server/api"),db=require("../server/database");
const app=express();app.use(express.json());app.use("/api",createApi());
let nextCall;
let sequence=[];
const originalFetch=global.fetch;
global.fetch=async url=>({ok:true,status:200,json:async()=>String(url).includes(":generateContent")?{candidates:[{content:{parts:[{functionCall:sequence.length?sequence.shift():nextCall}]}}]}:{models:[{name:"models/gemini-2.5-flash",supportedGenerationMethods:["generateContent"]}]}});
test.after(()=>{global.fetch=originalFetch;db.close();fs.rmSync(dir,{recursive:true,force:true});});
const product={name:"Brigadeiro",category:"Doces",costs:[{name:"Ingredientes",value:1.2},{name:"Embalagem",value:.3}],salePrice:5,targetMargin:30,units:100};
test("Zuni: ferramentas, confirmação persistente, isolamento e idempotência",async()=>{
 const a=request.agent(app),b=request.agent(app);
 for(const [agent,email] of [[a,"a@zuni.test"],[b,"b@zuni.test"]]){
  await agent.post("/api/auth/signup").send({name:"Teste Zuni",email,password:"SenhaTeste123!"}).expect(201);
  await agent.put("/api/company").send({name:"Confeitaria",operationType:"producao"}).expect(200);
 }
 nextCall={name:"create_product",args:product};
 await request(app).post("/api/ai/test").send({message:"Cadastre brigadeiro"}).expect(401);
 const prepared=await a.post("/api/ai/test").send({message:"Cadastre brigadeiro com meus dados"}).expect(200);
 const action=prepared.body.actions[0];assert.ok(action.id);
 await a.get("/api/company").expect(r=>assert.equal(r.body.products.length,0));
 await b.post("/api/ai/actions/"+action.id).send({decision:"confirm"}).expect(404);
 await a.get("/api/ai/conversations/"+prepared.body.conversationId).expect(200).expect(r=>assert.equal(r.body.actions[0].state,"pending"));
 const saved=await a.post("/api/ai/actions/"+action.id).send({decision:"confirm"}).expect(200);assert.equal(saved.body.state,"completed");
 await a.post("/api/ai/actions/"+action.id).send({decision:"confirm"}).expect(200);
 const company=await a.get("/api/company").expect(200);assert.equal(company.body.products.length,1);assert.equal(company.body.products[0].additionalCosts.length,2);
 await b.get("/api/company").expect(r=>assert.equal(r.body.products.length,0));
 nextCall={name:"update_product",args:{productId:saved.body.productId,product:{...product,salePrice:6}}};
 const update=await a.post("/api/ai/test").send({message:"Altere para seis reais",conversationId:prepared.body.conversationId}).expect(200);
 await a.post("/api/ai/actions/"+update.body.actions[0].id).send({decision:"confirm"}).expect(200);
 await a.get("/api/company").expect(r=>{assert.equal(r.body.products.length,1);assert.equal(r.body.products[0].salePrice,6);});
 nextCall={name:"create_product",args:{...product,name:"Cancelado"}};
 const cancel=await a.post("/api/ai/test").send({message:"Cadastre outro"}).expect(200);
 await a.post("/api/ai/actions/"+cancel.body.actions[0].id).send({decision:"cancel"}).expect(200);
 await a.post("/api/ai/actions/"+cancel.body.actions[0].id).send({decision:"confirm"}).expect(r=>assert.equal(r.body.state,"cancelled"));
 nextCall={name:"create_product",args:{...product,costs:[]}};
 await a.post("/api/ai/test").send({message:"Sem custos"}).expect(r=>assert.equal(r.body.actions.length,0));
 nextCall={name:"calculate_price",args:{unitDirectCost:1.5,salePrice:5,targetMargin:30,units:100}};
 await a.post("/api/ai/test").send({message:"Calcule"}).expect(r=>assert.match(r.body.reply,/Preço sugerido: R\$/));
 nextCall={name:"list_products",args:{}};
 await b.post("/api/ai/test").send({message:"Meus produtos"}).expect(r=>assert.match(r.body.reply,/Nenhum produto/));
 nextCall={name:"delete_all_products",args:{}};
 await a.post("/api/ai/test").send({message:"Ação inválida"}).expect(r=>assert.match(r.body.reply,/não disponível/));
 await a.get("/api/company").expect(r=>assert.equal(r.body.products.length,1));
 nextCall={name:"list_products",args:{}};
 sequence=[nextCall,{name:"update_product",args:{productId:saved.body.productId,product:{...product,salePrice:7}}}];
 const chain=await a.post("/api/ai/test").send({message:"Busque brigadeiro e altere para sete reais"}).expect(200);
 assert.equal(chain.body.actions.length,1);
 const stale=chain.body.actions[0].id;
 // Uma alteração posterior não pode ser sobrescrita pela proposta antiga.
 await db.query("UPDATE zuz_products SET sale_price=8 WHERE id=$1",[saved.body.productId]);
 await a.post("/api/ai/actions/"+stale).send({decision:"confirm"}).expect(409);
 nextCall={name:"create_product",args:{...product,name:"Concorrência"}};
 const concurrent=await a.post("/api/ai/test").send({message:"Cadastrar outro produto"}).expect(200);
 const aid=concurrent.body.actions[0].id;
 await Promise.all([a.post("/api/ai/actions/"+aid).send({decision:"confirm"}).expect(200),a.post("/api/ai/actions/"+aid).send({decision:"confirm"}).expect(200)]);
 await a.get("/api/company").expect(r=>assert.equal(r.body.products.length,2));
 await a.get("/api/pricing/history?productId="+saved.body.productId).expect(r=>assert.ok(r.body.history.length));
});

test("Zuni: cadastra custo unitário agregado sem inventar ingredientes",async()=>{
 const agent=request.agent(app);
 await agent.post("/api/auth/signup").send({name:"Teste Custo Agregado",email:"agregado@zuni.test",password:"SenhaTeste123!"}).expect(201);
 await agent.put("/api/company").send({name:"Brigadeiros",operationType:"producao"}).expect(200);
 nextCall={name:"create_product",args:{name:"Brigadeiro",category:"Confeitaria",costs:[{name:"Custo agregado por unidade (R$ 30 / 50)",value:0.6}],salePrice:1.2,targetMargin:50,units:50}};
 const proposed=await agent.post("/api/ai/test").send({message:"Cadastre meu brigadeiro com os valores que aprovei"}).expect(200);
 assert.equal(proposed.body.actions.length,1);
 const action=proposed.body.actions[0];
 assert.equal(action.product.costs.length,1);
 await agent.get("/api/company").expect(r=>assert.equal(r.body.products.length,0));
 await agent.post("/api/ai/actions/"+action.id).send({decision:"confirm"}).expect(200);
 await agent.get("/api/company").expect(r=>{
   assert.equal(r.body.products.length,1);
   assert.equal(r.body.products[0].additionalCosts.length,1);
   assert.equal(r.body.products[0].additionalCosts[0].value,0.6);
 });
});
